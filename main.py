# Sort alphabetically
@app.get("/sort")
async def sort():
    try:
        with closing(psycopg.connect(db)) as conn:
            cursor = conn.cursor()

            cursor.execute("""SELECT id, title, done
                              FROM tasks
                              ORDER BY title ASC;""")

            sorted = cursor.fetchall()
            print("tasks Table sorted succesfully.")

            return sorted

    except psycopg.Error as e:
        print(f"Error 500: Database error: {e}")
        raise HTTPException(status_code=500, detail={"error": "Database error"})


# Create task
@app.post("/tasks", status_code=201)
async def create_task(task: taskCreate):
    if not task.title or not task.title.strip():
        return JSONResponse(status_code=400, content={"error": "Title is empty."})

    task_id = insert_task(db, task.title.strip())

    print("Task created succesfully.")

    return {"id": task_id, "title": task.title.strip(), "done": 0}


# Update a task
@app.put("/tasks/{id}")
async def update(id: int, task: taskChange):
    if not task.title or not task.title.strip():
        return JSONResponse(status_code=400, content={"error": "Title is empty."})

    update_task(db, id, (task.title, task.done))
    print("Task updated succesfully.")

    return {"id": id, "title": task.title, "done": task.done}


# Delete task
@app.delete("/tasks/{id}", status_code=204)
async def delete(id: int):
    if not id:
        return JSONResponse(
            status_code=400, content={"error": "ID should be of int type."}
        )

    delete_task(db, id)
    print("Task deleted succesfully.")
