from fastapi import FastAPI, HTTPException
from fastapi.responses import JSONResponse
from pydantic import BaseModel
from contextlib import closing
from dotenv import load_dotenv
from typing import Literal
import os
import psycopg

# Initializing FastAPI()
app = FastAPI()
load_dotenv()

# Path to the Postgres database URL
db = os.getenv("DATABASE_URL")

if db is None:
    raise RuntimeError("DATABASE_URL is missing from your .env file")


# Creating task BaseModel
class taskCreate(BaseModel):
    title: str


# Updating task BaseModel
class taskChange(BaseModel):
    title: str
    done: Literal[0, 1]


# Insert task function
def insert_task(db, title):
    try:
        with closing(psycopg.connect(db)) as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO tasks (title, done)
                    VALUES (%s, %s)
                    RETURNING id
                    """,
                    (title, 0),
                )

                task_id = cursor.fetchone()[0]
                conn.commit()

                return task_id

    except psycopg.Error as e:
        print(f"Database error: {e}")
        raise HTTPException(
            status_code=500,
            detail={"error": "Database error"},
        )


# Update task function
def update_task(db, id, data):
    try:
        with closing(psycopg.connect(db)) as conn:
            cursor = conn.cursor()

            # Update task
            cursor.execute(
                """UPDATE tasks
                SET title = %s, done = %s
                WHERE id = %s;""",
                (*data, id),
            )

            if cursor.rowcount == 0:
                raise HTTPException(
                    status_code=404, detail={"error": "Task not found."}
                )
            conn.commit()

    except psycopg.Error as e:
        print(f"Error 500: Database error: {e}")
        raise HTTPException(status_code=500, detail={"error": "Database error"})


# Delete task function
def delete_task(db, id):
    try:
        with closing(psycopg.connect(db)) as conn:
            cursor = conn.cursor()

            cursor.execute("DELETE FROM tasks WHERE id = %s;", (id,))

            if cursor.rowcount == 0:
                raise HTTPException(
                    status_code=404, detail={"error": "Task not found."}
                )

            conn.commit()

    except psycopg.Error as e:
        print(f"Error 500: Database error: {e}")
        raise HTTPException(status_code=500, detail={"error": "Database error"})


# Create tasks table
create_table_query = """
CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    done INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0, 1))
);
"""
try:
    with closing(psycopg.connect(db)) as conn:
        cursor = conn.cursor()

        cursor.execute(create_table_query)
        conn.commit()
        print("Table created successfully.")

except psycopg.Error as e:
    print(f"Failed to create table: {e}")
    raise HTTPException(status_code=500, detail={"error": "Failed to create table."})


# Seeds three tasks if table is empty
def seed_tasks(db):
    sample_tasks = [
        ("Stretch your body", 0),
        ("Feed your cats", 0),
        ("Drink a full glass of water", 0),
    ]

    with closing(psycopg.connect(db)) as conn:
        cursor = conn.cursor()
        is_empty = cursor.execute("SELECT 1 FROM tasks LIMIT 1").fetchone() is None

        if is_empty:
            cursor.executemany(
                "INSERT INTO tasks (title, done) VALUES (%s, %s)",
                sample_tasks,
            )
            conn.commit()


# Runs once at startup, after the table has been created
seed_tasks(db)


